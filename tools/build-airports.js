#!/usr/bin/env node
/*
 * Builds the Departure Airport lists for every country except Nigeria (Nigeria is a curated list:
 * LISTS.AIRPORTS_NG in apps-script/Config.gs = EG_LISTS.AIRPORTS_NG in public/assets/js/lists.js).
 *
 * Source: OurAirports (https://ourairports.com/data/), public domain.
 * Filter: scheduled passenger service, has an IATA code, and either a large airport or a name
 *         containing "International". Countries are keyed by the names in COUNTRIES (Config.gs).
 * Writes (same data, keep them in one commit):
 *   public/assets/data/airports.json   lazy-loaded by the website
 *   apps-script/Airports.gs            used by the web app to validate the chosen airport
 * Usage: node tools/build-airports.js        (needs internet; Node 18+; no dependencies)
 * Then:  node tools/check-lists.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.resolve(__dirname, '..');
const BASE = 'https://davidmegginson.github.io/ourairports-data/';
// OurAirports country names that differ from ours (ISO code → name in COUNTRIES)
const NAME_BY_CODE = {
  CV: 'Cabo Verde', CG: 'Congo (Republic)', CD: 'Congo (Democratic Republic)',
  PS: 'Palestine', ST: 'São Tomé and Príncipe',
};

function parseCsv(text) {
  const rows = []; let row = [], f = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) { if (c === '"') { if (text[i + 1] === '"') { f += '"'; i++; } else q = false; } else f += c; }
    else if (c === '"') q = true;
    else if (c === ',') { row.push(f); f = ''; }
    else if (c === '\n') { row.push(f); rows.push(row); row = []; f = ''; }
    else if (c !== '\r') f += c;
  }
  if (f || row.length) { row.push(f); rows.push(row); }
  const head = rows.shift();
  return rows.filter((r) => r.length === head.length).map((r) => Object.fromEntries(head.map((h, i) => [h, r[i]])));
}

async function get(file) {
  const res = await fetch(BASE + file);
  if (!res.ok) throw new Error(file + ': HTTP ' + res.status);
  return res.text();
}

(async () => {
  const gas = { Math };
  vm.createContext(gas);
  vm.runInContext(fs.readFileSync(path.join(root, 'apps-script/Config.gs'), 'utf8') + '\n;this.__C = COUNTRIES;', gas);
  const ours = new Set(gas.__C);

  const [countries, airports] = await Promise.all([get('countries.csv'), get('airports.csv')]);
  const nameByCode = {};
  parseCsv(countries).forEach((c) => {
    const name = NAME_BY_CODE[c.code] || c.name;
    if (ours.has(name)) nameByCode[c.code] = name;
  });

  const all = parseCsv(airports);
  const out = {};
  let count = 0;
  all.forEach((a) => {
    if (a.scheduled_service !== 'yes' || !/^[A-Z]{3}$/.test(a.iata_code)) return;
    if (a.type !== 'large_airport' && !/international/i.test(a.name)) return;
    if (a.type !== 'large_airport' && a.type !== 'medium_airport') return;
    const country = nameByCode[a.iso_country];
    if (!country || country === 'Nigeria') return;
    (out[country] = out[country] || []).push([a.iata_code, a.name.trim(), (a.municipality || '').trim()]);
    count++;
  });
  const sorted = {};
  Object.keys(out).sort((a, b) => a.localeCompare(b)).forEach((k) => {
    sorted[k] = out[k].sort((x, y) => (x[2] || x[1]).localeCompare(y[2] || y[1]) || x[0].localeCompare(y[0]));
  });

  const json = JSON.stringify(sorted);
  fs.mkdirSync(path.join(root, 'public/assets/data'), { recursive: true });
  fs.writeFileSync(path.join(root, 'public/assets/data/airports.json'), json + '\n');
  const today = new Date().toISOString().slice(0, 10);
  const gs = '/**\n' +
    ' * GENERATED by tools/build-airports.js on ' + today + ' — do not edit by hand.\n' +
    ' * Departure airports per country (except Nigeria: LISTS.AIRPORTS_NG in Config.gs).\n' +
    ' * Source: OurAirports (ourairports.com/data), public domain. Same data as\n' +
    ' * public/assets/data/airports.json (checked by tools/check-lists.js).\n' +
    ' * Format: { "<country as in COUNTRIES>": [[IATA, airport name, city], …] }\n' +
    ' */\n' +
    'const AIRPORTS = {\n' +
    Object.keys(sorted).map((k) => '  ' + JSON.stringify(k) + ': ' + JSON.stringify(sorted[k]) + ',').join('\n') +
    '\n};\n';
  fs.writeFileSync(path.join(root, 'apps-script/Airports.gs'), gs);
  console.log(`${count} airports in ${Object.keys(sorted).length} countries → airports.json ${(json.length / 1024).toFixed(0)} KB, Airports.gs ${(gs.length / 1024).toFixed(0)} KB`);
})().catch((e) => { console.error(e); process.exit(1); });
